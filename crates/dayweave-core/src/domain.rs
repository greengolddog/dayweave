struct Rfc3339Ref<'a>(&'a OffsetDateTime);

impl Serialize for Rfc3339Ref<'_> {
    fn serialize<S>(&self, serializer: S) -> Result<S::Ok, S::Error>
    where
        S: serde::Serializer,
    {
        use time::format_description::well_known::Rfc3339;

        self.0
            .format(&Rfc3339)
            .map_err(serde::ser::Error::custom)?
            .serialize(serializer)
    }
}

mod qualified_offset_datetime_option {
    use serde::{Deserialize, Serialize};
    use time::{OffsetDateTime, format_description::well_known::Rfc3339};

    use super::{ConstraintStrength, Qualified, Rfc3339Ref};

    #[allow(clippy::ref_option)] // Serde's `with` adapter requires a reference to the field type.
    pub fn serialize<S>(
        value: &Option<Qualified<OffsetDateTime>>,
        serializer: S,
    ) -> Result<S::Ok, S::Error>
    where
        S: serde::Serializer,
    {
        value.as_ref().map(WireRef).serialize(serializer)
    }

    pub fn deserialize<'de, D>(
        deserializer: D,
    ) -> Result<Option<Qualified<OffsetDateTime>>, D::Error>
    where
        D: serde::Deserializer<'de>,
    {
        let wire = Option::<Wire>::deserialize(deserializer)?;
        wire.map(|wire| {
            OffsetDateTime::parse(&wire.value, &Rfc3339)
                .map(|value| Qualified {
                    value,
                    strength: wire.strength,
                })
                .map_err(serde::de::Error::custom)
        })
        .transpose()
    }

    struct WireRef<'a>(&'a Qualified<OffsetDateTime>);

    impl Serialize for WireRef<'_> {
        fn serialize<S>(&self, serializer: S) -> Result<S::Ok, S::Error>
        where
            S: serde::Serializer,
        {
            use serde::ser::SerializeStruct as _;

            let mut state = serializer.serialize_struct("QualifiedOffsetDateTime", 2)?;
            state.serialize_field("value", &Rfc3339Ref(&self.0.value))?;
            state.serialize_field("strength", &self.0.strength)?;
            state.end()
        }
    }

    #[derive(Deserialize)]
    #[serde(deny_unknown_fields)]
    struct Wire {
        value: String,
        strength: ConstraintStrength,
    }
}

mod item_datetime_map_rfc3339 {
    use std::collections::BTreeMap;

    use serde::Deserialize;
    use time::{OffsetDateTime, format_description::well_known::Rfc3339};

    use super::{ItemId, Rfc3339Ref};

    pub fn serialize<S>(
        value: &BTreeMap<ItemId, OffsetDateTime>,
        serializer: S,
    ) -> Result<S::Ok, S::Error>
    where
        S: serde::Serializer,
    {
        use serde::ser::SerializeMap as _;

        let mut map = serializer.serialize_map(Some(value.len()))?;
        for (key, instant) in value {
            map.serialize_entry(key, &Rfc3339Ref(instant))?;
        }
        map.end()
    }

    pub fn deserialize<'de, D>(
        deserializer: D,
    ) -> Result<BTreeMap<ItemId, OffsetDateTime>, D::Error>
    where
        D: serde::Deserializer<'de>,
    {
        BTreeMap::<ItemId, String>::deserialize(deserializer)?
            .into_iter()
            .map(|(key, value)| {
                OffsetDateTime::parse(&value, &Rfc3339)
                    .map(|instant| (key, instant))
                    .map_err(serde::de::Error::custom)
            })
            .collect()
    }
}

