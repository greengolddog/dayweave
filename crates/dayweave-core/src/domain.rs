#[derive(Debug, Error, Clone, PartialEq, Eq)]
pub enum HierarchyError {
    #[error("duplicate item id {0}")]
    DuplicateItem(ItemId),
    #[error("item {item} references missing parent {parent}")]
    MissingParent { item: ItemId, parent: ItemId },
    #[error("hierarchy cycle includes item {0}")]
    Cycle(ItemId),
}

/// Calculates expected duration for every parent without scheduling parents as
/// extra work. A parent's own estimate is included only when `has_own_effort`
/// is true; a leaf always includes its own estimate.
///
/// # Errors
///
/// Returns an error when IDs are duplicated, a parent is missing, or the
/// hierarchy contains a cycle.
pub fn roll_up_expected_durations(
    items: &[WorkItem],
) -> Result<BTreeMap<ItemId, Minutes>, HierarchyError> {
    let by_id: BTreeMap<_, _> = items.iter().map(|item| (item.id, item)).collect();
    if by_id.len() != items.len() {
        let mut seen = BTreeSet::new();
        if let Some(duplicate) = items
            .iter()
            .map(|item| item.id)
            .find(|id| !seen.insert(*id))
        {
            return Err(HierarchyError::DuplicateItem(duplicate));
        }
    }

    let mut children: BTreeMap<ItemId, Vec<ItemId>> = BTreeMap::new();
    for item in items {
        if let Some(parent) = item.parent_id {
            if !by_id.contains_key(&parent) {
                return Err(HierarchyError::MissingParent {
                    item: item.id,
                    parent,
                });
            }
            children.entry(parent).or_default().push(item.id);
        }
    }

    let mut result = BTreeMap::new();
    for id in by_id.keys() {
        let mut visiting = BTreeSet::new();
        visit_rollup(*id, &by_id, &children, &mut visiting, &mut result)?;
    }
    Ok(result)
}

fn visit_rollup(
    id: ItemId,
    by_id: &BTreeMap<ItemId, &WorkItem>,
    children: &BTreeMap<ItemId, Vec<ItemId>>,
    visiting: &mut BTreeSet<ItemId>,
    result: &mut BTreeMap<ItemId, Minutes>,
) -> Result<u32, HierarchyError> {
    if let Some(value) = result.get(&id) {
        return Ok(value.get());
    }
    if !visiting.insert(id) {
        return Err(HierarchyError::Cycle(id));
    }

    let item = by_id[&id];
    let child_ids = children.get(&id).map_or(&[][..], Vec::as_slice);
    let mut total = 0_u32;
    if child_ids.is_empty() || item.has_own_effort {
        total = item
            .duration
            .map_or(0, |duration| duration.planning_minutes().get());
    }
    for child in child_ids {
        total = total.saturating_add(visit_rollup(*child, by_id, children, visiting, result)?);
    }
    visiting.remove(&id);
    result.insert(id, Minutes(total));
    Ok(total)
}
