#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
#[serde(deny_unknown_fields)]
pub struct DailyTimeWindow {
    pub weekdays: BTreeSet<DayOfWeek>,
    /// Inclusive minute since local midnight, 0..=1439.
    pub start_minute: u16,
    /// Exclusive minute since local midnight, 1..=1440. A value lower than
    /// `start_minute` denotes a window crossing midnight.
    pub end_minute: u16,
}

impl DailyTimeWindow {
    #[must_use]
    pub fn contains(&self, start: OffsetDateTime, end: OffsetDateTime) -> bool {
        let weekday = DayOfWeek::from_time(start.weekday());
        if !self.weekdays.is_empty() && !self.weekdays.contains(&weekday) {
            return false;
        }
        let start_minute = u16::from(start.hour()) * 60 + u16::from(start.minute());
        let end_minute = u16::from(end.hour()) * 60 + u16::from(end.minute());
        if self.start_minute < self.end_minute {
            start_minute >= self.start_minute
                && (end.date() == start.date())
                && end_minute <= self.end_minute
        } else {
            // Crossing-midnight window, for example 22:00–02:00.
            start_minute >= self.start_minute || end_minute <= self.end_minute
        }
    }
}

